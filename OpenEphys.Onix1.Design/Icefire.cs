        /// <summary>
        /// The 256-entry icefire table with full opacity, packed as ABGR, its middle taken down to black.
        /// </summary>
        public static readonly uint[] Map = BuildMap();

        // NB: icefire's middle is a 12% grey, which reads as a haze over the black plot. Each half has its
        // innermost color subtracted, fully at the middle and fading to nothing at the ends, so the middle is
        // black and the ends are unchanged.
        static uint[] BuildMap()
        {
            var entries = Data.Length / 3;
            var half = entries / 2;
            var map = new uint[entries];
            for (int i = 0; i < entries; i++)
            {
                var inner = i < half ? half - 1 : half;
                var weight = i < half ? i / (float)(half - 1) : (entries - 1 - i) / (float)(entries - 1 - half);
                byte Channel(int c) =>
                    (byte)(Math.Max(0f, Data[i * 3 + c] - weight * Data[inner * 3 + c]) * 255f + 0.5f);

                map[i] = 0xFF000000u | (uint)Channel(2) << 16 | (uint)Channel(1) << 8 | Channel(0);
            }
            return map;
        }
